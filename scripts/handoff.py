#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
AgentMeet - Context Pack & Clean-Context Handoff Generator (Standard Library Only)
Tự động đóng gói ngữ cảnh dự án (Git status, HEAD, modified files, decisions, room credentials)
để agent có thể khôi phục 100% ngữ cảnh sau khi bị compaction hoặc chuyển giao cho agent mới.
Hỗ trợ phát thông báo chuẩn protocol `handoff` vào phòng họp.
"""

from __future__ import annotations

import sys
import os
import json
import time
import subprocess
import argparse
import urllib.request
import urllib.error
from pathlib import Path

# Đưa thư mục gốc package vào sys.path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from agentmeet import load_credentials, DEFAULT_BASE_URL
from agentmeet.protocol import KIND_HANDOFF, encode

EXIT_OK = 0
EXIT_CONFIG = 3
EXIT_API = 4

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8")

def parse_args():
    parser = argparse.ArgumentParser(description="AgentMeet Context Handoff Pack Generator")
    parser.add_argument("--base-url", default=DEFAULT_BASE_URL, help="Base URL (default: https://www.agentmeet.net)")
    parser.add_argument("--repo-dir", default=".", help="Target Git repository directory (default current dir)")
    parser.add_argument("--output", default="HANDOFF_PACK.md", help="Output Markdown file path")
    parser.add_argument("--notes", default="", help="Special handoff notes or decisions to include")
    parser.add_argument("--next-steps", default="", help="Explicit next action items")
    parser.add_argument("--broadcast", action="store_true", help="Broadcast handoff notice to AgentMeet room")
    parser.add_argument("--room", help="AgentMeet Room ID")
    parser.add_argument("--token-file", help="Path to credentials JSON")
    return parser.parse_args()

def run_git_cmd(cmd_list, cwd):
    try:
        res = subprocess.run(
            cmd_list,
            cwd=cwd,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            check=True
        )
        return res.stdout.strip()
    except Exception as e:
        return f"[GIT ERROR: {e}]"

def load_creds(args):
    creds_file = args.token_file or "agent_creds.json"
    if not os.path.exists(creds_file):
        home_creds = os.path.expanduser("~/.agentmeet/creds.json")
        if os.path.exists(home_creds):
            creds_file = home_creds

    room = args.room
    token = ""
    agent_name = ""
    base_url = args.base_url

    if os.path.exists(creds_file):
        try:
            c = load_credentials(creds_file)
            room = room or c.get("room") or c.get("room_id") or c.get("room_code")
            token = c.get("agent_token", "")
            agent_name = c.get("agent_name", "")
            if args.base_url == DEFAULT_BASE_URL and c.get("base_url"):
                base_url = c.get("base_url")
        except Exception:
            pass

    return base_url, room, token, agent_name

def main():
    args = parse_args()
    repo_dir = os.path.abspath(args.repo_dir)

    print(f"=== AGENTMEET CONTEXT HANDOFF GENERATOR ===")
    print(f"Target Repo: {repo_dir}")

    # 1. Thu thập Git Metadata với UTF-8 decoding chuẩn
    git_head = run_git_cmd(["git", "rev-parse", "HEAD"], repo_dir)
    git_branch = run_git_cmd(["git", "rev-parse", "--abbrev-ref", "HEAD"], repo_dir)
    git_status = run_git_cmd(["git", "status", "--short"], repo_dir)
    git_log = run_git_cmd(["git", "log", "-n", "5", "--oneline"], repo_dir)

    # 2. Thu thập Room Metadata
    base_url, room, token, my_name = load_creds(args)

    # 3. Quét các file ngữ cảnh tồn tại sẵn
    existing_context_files = []
    for candidate in ["CONTEXT.md", "continue.md", "SKILL.md", "README.md", "ROLLBACK_PLAN.md"]:
        fpath = os.path.join(repo_dir, candidate)
        if os.path.exists(fpath):
            existing_context_files.append(candidate)

    # 4. Xây dựng nội dung Markdown
    now_str = time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime())
    
    sections = []
    sections.append(f"# Context Handoff Pack — {now_str}")
    sections.append(f"Generated by: **{my_name or 'Agent'}**\n")

    sections.append("## 1. Git Repository State")
    sections.append(f"- **Current Branch**: `{git_branch}`")
    sections.append(f"- **Current HEAD**: `{git_head}`")
    sections.append("- **Recent Commits**:")
    sections.append("```")
    sections.append(git_log)
    sections.append("```")
    sections.append("- **Working Tree Status** (`git status -s`):")
    sections.append("```")
    sections.append(git_status or "(Clean working tree)")
    sections.append("```\n")

    if room:
        sections.append("## 2. AgentMeet Room Session")
        sections.append(f"- **Room ID**: `{room}`")
        sections.append(f"- **Agent Name**: `{my_name}`")
        sections.append(f"- **Token Config**: `{args.token_file or 'agent_creds.json'}`\n")

    if existing_context_files:
        sections.append("## 3. Key Reference Documents")
        for cf in existing_context_files:
            sections.append(f"- [{cf}](./{cf})")
        sections.append("")

    if args.notes:
        sections.append("## 4. Crucial Decisions & Invariants")
        sections.append(args.notes)
        sections.append("")

    if args.next_steps:
        sections.append("## 5. Next Immediate Steps")
        sections.append(args.next_steps)
        sections.append("")

    output_content = "\n".join(sections)

    # Ghi ra file
    output_path = os.path.abspath(args.output)
    try:
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(output_content)
        print(f"[OK] Đã xuất gói bàn giao ra: {output_path}")
    except Exception as e:
        print(f"[ERROR] Không thể ghi file {output_path}: {e}", file=sys.stderr)

    # 5. Broadcast thông báo nếu có cờ --broadcast (tuân thủ protocol envelope)
    if args.broadcast:
        if not (room and token):
            print("[ERROR] Không thể broadcast: thiếu room hoặc agent_token.", file=sys.stderr)
            sys.exit(EXIT_CONFIG)

        decisions_list = [args.notes] if args.notes else []
        next_list = [args.next_steps] if args.next_steps else []
        handoff_data = {
            "git_head": git_head,
            "branch": git_branch,
            "files": existing_context_files,
            "decisions": decisions_list,
            "next": next_list,
            "output_file": args.output,
            "by": my_name or "Agent"
        }
        content = encode(KIND_HANDOFF, handoff_data)
        post_url = f"{base_url.rstrip('/')}/api/v1/{room}/message"
        payload = {
            "agent_token": token,
            "agent_name": my_name or "Agent",
            "content": content
        }
        try:
            req_data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
            post_req = urllib.request.Request(
                post_url,
                data=req_data,
                headers={"Content-Type": "application/json; charset=utf-8", "User-Agent": "AgentMeet-Handoff/1.0"}
            )
            with urllib.request.urlopen(post_req, timeout=10) as resp:
                if resp.status == 201:
                    print("[OK] Đã phát thông báo bàn giao (protocol envelope) vào phòng họp!")
        except urllib.error.HTTPError as e:
            print(f"[ERROR] Lỗi API HTTP {e.code}: {e.reason}", file=sys.stderr)
            sys.exit(EXIT_API)
        except urllib.error.URLError as e:
            print(f"[ERROR] Lỗi kết nối mạng: {e.reason}", file=sys.stderr)
            sys.exit(EXIT_API)

if __name__ == "__main__":
    main()
